COMPILED = [(re.compile(p), tool, args) for p, tool, args in RULES]


def match(text: str):
    """(инструмент, аргументы) — если фраза целиком частая команда; иначе None — это модели."""
    t = _norm(text)
    for rx, tool, args in COMPILED:
        m = rx.fullmatch(t)
        if m:
            a = args(m) if callable(args) else dict(args)
            if any(v is None for v in a.values()):        # «на пятнадцатый стол» — числа нет
                return None
            return tool, a
    return None
